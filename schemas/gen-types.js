#!/usr/bin/env node
'use strict';

// Generates schemas/types.d.ts from the *.schema.json files (plan 1.1, D15:
// one schema source, TS types generated). Dependency-free and limited to the
// keywords schemas/index.js supports.
//
//   node schemas/gen-types.js           write types.d.ts
//   node schemas/gen-types.js --check   exit 1 if types.d.ts is stale
//
// Each schema becomes an exported type named after its title; each $defs entry
// becomes `<Title><Def>` (job.schema.json#/$defs/story -> JobStory).

const fs = require('fs');
const path = require('path');
const { NAMES, schema } = require('./index');

const OUT = path.join(__dirname, 'types.d.ts');
const pascal = (s) => s.replace(/(^|[_-])([a-z])/g, (_, __, c) => c.toUpperCase());
const titleOf = (file) => schema(file.replace(/\.schema\.json$/, '')).title;

function refName(ref, file) {
  const [doc, frag = ''] = ref.split('#');
  const target = doc || file;
  const def = frag.split('/').filter(Boolean);
  const base = titleOf(target);
  return def.length ? `${base}${pascal(def[def.length - 1])}` : base;
}

function lit(v) {
  return v === null ? 'null' : JSON.stringify(v);
}

function ts(s, file, indent) {
  if (s === true || s === undefined) return 'unknown';
  if (s === false) return 'never';
  if (s.$ref) return refName(s.$ref, file);
  if ('const' in s) return lit(s.const);
  if (s.enum) return s.enum.map(lit).join(' | ');
  if (s.anyOf) return s.anyOf.map((x) => ts(x, file, indent)).join(' | ');
  const types = Array.isArray(s.type) ? s.type : s.type ? [s.type] : [];
  if (!types.length) return 'unknown';
  return types.map((t) => {
    if (t === 'integer' || t === 'number') return 'number';
    if (t === 'string' || t === 'boolean' || t === 'null') return t;
    if (t === 'array') {
      const inner = ts(s.items, file, indent);
      return /[ |]/.test(inner) ? `Array<${inner}>` : `${inner}[]`;
    }
    if (t === 'object') return objectType(s, file, indent);
    return 'unknown';
  }).join(' | ');
}

function objectType(s, file, indent) {
  const pad = '  '.repeat(indent + 1);
  const req = new Set(s.required || []);
  const lines = [];
  for (const [k, p] of Object.entries(s.properties || {})) {
    if (p.description) lines.push(`${pad}/** ${p.description.replace(/\*\//g, '* /')} */`);
    const key = /^[A-Za-z_$][\w$]*$/.test(k) ? k : JSON.stringify(k);
    lines.push(`${pad}${key}${req.has(k) ? '' : '?'}: ${ts(p, file, indent + 1)};`);
  }
  if (s.additionalProperties !== false) lines.push(`${pad}[key: string]: unknown;`);
  return `{\n${lines.join('\n')}\n${'  '.repeat(indent)}}`;
}

function generate() {
  const out = [
    '// Generated by schemas/gen-types.js from schemas/*.schema.json. Do not edit by hand:',
    '// change the schema, then run `node schemas/gen-types.js`.',
    '',
  ];
  for (const n of NAMES) {
    const file = `${n}.schema.json`;
    const s = schema(n);
    const doc = (d) => (d ? [`/** ${d.replace(/\*\//g, '* /')} */`] : []);
    out.push(...doc(s.description), `export type ${s.title} = ${ts({ ...s, $defs: undefined }, file, 0)};`, '');
    for (const [k, d] of Object.entries(s.$defs || {})) {
      out.push(...doc(d.description), `export type ${s.title}${pascal(k)} = ${ts(d, file, 0)};`, '');
    }
  }
  return out.join('\n');
}

module.exports = { generate, OUT };

if (require.main === module) {
  const text = generate();
  if (process.argv.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== text) {
      console.error('schemas/types.d.ts is stale: run `node schemas/gen-types.js`');
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(process.cwd(), OUT)}`);
  }
}
